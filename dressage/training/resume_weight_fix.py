"""Resume weight-sync fix (runtime plugin, no slime source edit).

BUG (see memory gb10-resume-base-weight-broadcast): on resume, initialize_model_and_optimizer
restores the fp32 optimizer MASTER params to iter-N but leaves the bf16 model `param.data` at
BASE (bf16 materializes from master only at the first _copy_main_params_to_model_params). slime's
initial weight broadcast reads the LIVE bf16 `param.data` (named_params_and_buffers), so the FIRST
post-resume rollout is generated by SGLang with BASE weights: train_rollout_logprob_abs_diff spikes
~11x (0.145 vs ~0.013) and reward drops to base level for exactly one step, then self-corrects.

FIX: right after MegatronTrainRayActor.init() loads the checkpoint (and does its own backup("actor")),
materialize the bf16 model params from the loaded master via the actor's own _restore_actor_from_master()
BEFORE the first broadcast, then refresh the actor backup hash so the master-param safety assertions
stay consistent. SELF-VERIFYING: hashes the broadcast-source params before/after; a CHANGE proves bf16
was stale (a real resume we just fixed), NO change = from-base/already-consistent (harmless no-op).

Env-gated: USE_RESUME_WEIGHT_FIX=1. Fully wrapped: any failure logs and leaves the launch unchanged.
"""
import os


def _enabled() -> bool:
    return os.environ.get("USE_RESUME_WEIGHT_FIX", "0").lower() in ("1", "true", "yes", "on")


def install() -> None:
    import logging
    log = logging.getLogger(__name__)
    try:
        if not _enabled():
            return
        from slime.backends.megatron_utils.actor import MegatronTrainRayActor as A
        from slime.utils.tensor_backper import _compute_hash_dict

        if getattr(A.init, "_resume_weight_fix_patched", False):
            log.warning("[resume-weight-fix] already installed; skipping")
            return

        _orig_init = A.init

        def _patched_init(self, *args, **kwargs):
            ret = _orig_init(self, *args, **kwargs)
            try:
                bk = getattr(self, "weights_backuper", None)
                sg = getattr(bk, "_source_getter", None)
                if not (sg and hasattr(self, "_restore_actor_from_master") and getattr(self, "optimizer", None) is not None):
                    log.warning("[resume-weight-fix] prerequisites absent (no master/backuper); no-op")
                    return ret
                before = _compute_hash_dict({k: v for k, v in dict(sg()).items()})
                # Materialize bf16 model params from the freshly-loaded fp32 optimizer master.
                self._restore_actor_from_master()
                after = _compute_hash_dict({k: v for k, v in dict(sg()).items()})
                changed = sum(1 for k in after if before.get(k) != after[k])
                # Refresh the actor backup hash so master-param get()/restore() asserts match the corrected bf16.
                try:
                    if "actor" in bk.backup_tags:
                        bk.backup("actor")
                except Exception as e2:
                    log.warning(f"[resume-weight-fix] backup-refresh skipped ({e2!r})")
                if changed:
                    log.warning(
                        f"[resume-weight-fix] MATERIALIZED bf16 from master: {changed}/{len(after)} tensors CHANGED "
                        f"-> RESUME detected; initial broadcast would have shipped STALE(base) weights; NOW FIXED"
                    )
                else:
                    log.warning(
                        f"[resume-weight-fix] no-op: bf16 already == master ({len(after)} tensors) "
                        f"(from-base start or already-consistent)"
                    )
            except Exception as e:
                log.warning(f"[resume-weight-fix] skipped ({e!r}); initial broadcast unchanged")
            return ret

        _patched_init._resume_weight_fix_patched = True
        A.init = _patched_init
        log.warning("[resume-weight-fix] runtime plugin installed (USE_RESUME_WEIGHT_FIX=1)")
    except Exception as e:
        log.warning(f"[resume-weight-fix] install failed ({e!r}); disabled")
